         String group = input.id();

         for (Entry<String, String> entry : groupIds.entrySet()) {
            for (String prefix : entry.getValue().split(",")) {
               if (!prefix.isBlank() && input.id().toLowerCase(Locale.ROOT).startsWith(prefix.strip().toLowerCase(Locale.ROOT))) {
                  group = entry.getKey();
               }
            }
         }

